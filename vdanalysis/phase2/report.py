"""Markdown report generator for Phase 2 (analysis/phase2/analysis_report.md).

Pure formatting: takes the tables produced by ``run_phase2_mode`` and writes a
single readable page. It never recomputes anything and never decides anything;
a hypothesis whose verdict is withheld is shown as "pending".
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from ..run_analysis import _fmt, _md_table

VERDICT = {True: "supported", False: "not supported", None: "pending / not testable"}


def _verdict(v: Any) -> str:
    return VERDICT.get(v if isinstance(v, bool) else None)


def _ci(r: dict) -> str:
    lo, hi = r.get("ci95_lo"), r.get("ci95_hi")
    return "" if lo is None or hi is None else f"[{lo:.3f}, {hi:.3f}]"


def _section(title: str, rows: list[dict], cols: list[str], note: str = "") -> str:
    out = [f"\n## {title}\n"]
    if note:
        out.append(note + "\n")
    out.append(_md_table(rows, [c for c in cols if rows and any(c in r for r in rows)]) if rows else "_(no rows)_\n")
    return "\n".join(out)


def build_report(cfg, res: dict[str, Any]) -> str:
    t = res["tables"]
    lines = ["# Phase 2 analysis report\n",
             "Generated by `vdanalysis/phase2/report.py` from the tables in `analysis_out_v3/`. "
             "Thresholds and definitions are those of PLAN_PHASE2.md; this page decides nothing by itself.\n"]
    if res.get("missing"):
        lines.append(f"**{len(res['missing'])} runs missing - results below are partial.**\n")
    if res.get("warnings"):
        lines.append(f"**{len(res['warnings'])} loader warnings (see run_warnings.json).**\n")
    lines.append(f"W3 / P7: {res.get('p7', 'n/a')}\n")

    hyp = [dict(r, verdict=_verdict(r.get("supported")), ci95=_ci(r)) for r in t.get("hypotheses_p", [])]
    main = [r for r in hyp if r.get("view") == "all"]
    lines.append(_section("Hypotheses P1-P6 (all trials)", main,
                          ["hypothesis", "variant", "statement", "n_decisions", "n_flipped", "value", "ci95",
                           "threshold", "comparison_value", "verdict", "note"],
                          "Intervals are exact Clopper-Pearson 95%. P2 and P6 verdicts are withheld until the "
                          "meaning of 'replicate' is fixed in the plan (see the variants table below)."))
    lines.append(_section("P2 / P6 under each reading of 'replicate'",
                          [r for r in t.get("p2_p6_replication_variants", []) if r.get("view") == "all"],
                          ["hypothesis", "direction_rule", "multi_factor_rule", "n_reference_decisions", "n_replicated",
                           "threshold", "would_be_supported"]))
    lines.append(_section("P7 (descriptive, only if W3 ran)", t.get("p7", []),
                          ["protocol", "gate", "suite", "n_decisions", "n_differ", "share", "ci95_lo", "ci95_hi",
                           "differing"]))
    lines.append(_section("Controls (primary gate and secondary full-score gate)", t.get("controls_summary", []),
                          ["control", "kind", "gate", "n_decisions", "n_flagged", "false_alarm_rate", "detection_rate",
                           "ci95_lo", "ci95_hi", "n_models", "n_models_with_flag", "full_n_flagged",
                           "full_false_alarm_rate", "full_detection_rate", "full_ci95_lo", "full_ci95_hi"]))
    lines.append(_section("Flip rate by factor (all trials, main variant, all pairs)",
                          [r for r in t.get("flip_rates_by_factor", []) if r.get("pair_subset") == "all_pairs"],
                          ["factor", "variant", "n_decisions", "n_flips", "flip_rate", "n_sign_flips"]))
    lines.append(_section("Greedy-only and sampled-only views: P1 / P3 / P4 / P5",
                          [dict(r, verdict=_verdict(r.get("supported")), ci95=_ci(r)) for r in hyp
                           if r.get("view") in ("greedy", "sampled") and r["hypothesis"] in ("P1", "P3", "P4", "P5")],
                          ["view", "hypothesis", "variant", "n_decisions", "n_flipped", "value", "ci95", "verdict"],
                          "Descriptive: the same computations on the greedy trial only / the sampled trials only."))
    lines.append(_section("Hardware noise: D laptop vs D Kaggle (per model, Kaggle minus laptop)", t.get("hw_noise_runs", []),
                          ["model", "suite", "n_stress_records", "stress_diff", "baseline_diff", "greedy_stress_diff",
                           "prompts_identical"]))
    lines.append(_section("Hardware noise: per pair", t.get("hw_noise_pairs", []),
                          ["pair", "suite", "laptop_diff", "kaggle_diff", "hardware_diff", "laptop_label",
                           "kaggle_label", "labels_agree"]))
    lines.append(_section("F5 per-model shift (same hardware) vs A/A noise", t.get("f5_shift_vs_aa", []),
                          ["model", "suite", "baseline_protocol", "f5_shift", "aa_max_abs_diff", "aa_p95_abs_diff",
                           "exceeds_aa_max", "exceeds_aa_p95"]))
    lines.append(_section("New flips not seen in Phase 1", t.get("new_flips", []),
                          ["factor", "pair", "suite", "d_label", "factor_label", "confounding"]))
    if "human_agreement" in t:
        lines.append(_section("Human labels (W6)", t["human_agreement"], ["rater_a", "rater_b", "kind", "n", "percent_agree", "kappa"]))
    return "\n".join(lines)


def write_report(cfg, res: dict[str, Any], path: Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_report(cfg, res), encoding="utf-8")
    return path
